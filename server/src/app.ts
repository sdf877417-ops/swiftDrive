import express from "express";
import cors from "cors";
import helmet from "helmet";
import cookieParser from "cookie-parser";
import { rateLimit } from "express-rate-limit";
import { env } from "./config/env.js";
import authRoutes from "./routes/auth.js";
import fileRoutes from "./routes/files.js";
import { errorHandler,notFound } from "./middleware/errors.js";
const app=express();
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({origin:env.CLIENT_URL,credentials:true,methods:["GET","POST","DELETE","OPTIONS"],allowedHeaders:["Content-Type"]}));
app.use(express.json({limit:"32kb"}));app.use(cookieParser());
app.use("/api",rateLimit({windowMs:15*60*1000,limit:300,standardHeaders:true,legacyHeaders:false}));
app.get("/api/health",(_req,res)=>res.json({status:"ok",service:"swiftdrive-api"}));
app.use("/api/auth",authRoutes);app.use("/api/files",fileRoutes);
app.use(notFound);app.use(errorHandler);
export default app;
